import type { InvestigationDetailResponse } from '@/types/domain';

export function generateMarkdownReport(detail: InvestigationDetailResponse): string {
  const timestamp = new Date().toLocaleDateString('en-US', {
    year: 'numeric',
    month: 'long',
    day: 'numeric',
  });

  const lines: string[] = [];

  // Title and Metadata
  lines.push(`# Product Discovery Brief: ${detail.user_query}`);
  lines.push(`**Generated by PMLytics AI** | Date: ${timestamp} | ID: \`${detail.investigation_id}\``);
  lines.push(`**Status:** ${detail.status.toUpperCase()}`);
  if (detail.scope) {
    const start = detail.scope.start_time ? new Date(detail.scope.start_time).toLocaleDateString() : 'Unbounded';
    const end = detail.scope.end_time ? new Date(detail.scope.end_time).toLocaleDateString() : 'Present';
    lines.push(`**Analysis Window:** ${start} to ${end}`);
  }
  lines.push('\n---\n');

  // Executive Recommendation
  if (detail.recommendation) {
    const rec = detail.recommendation;
    lines.push('## Executive Recommendation');
    lines.push(`> ${rec.recommendation}`);
    lines.push(`\n**Confidence Level:** \`${(rec.confidence || 'medium').toUpperCase()}\``);
    lines.push(`**Recommendation Type:** \`${rec.recommendation_type || 'reliability'}\``);

    if (rec.problem_statement) {
      lines.push(`\n### Problem Statement\n${rec.problem_statement}`);
    }
    if (rec.why_it_matters) {
      lines.push(`\n### Why It Matters\n${rec.why_it_matters}`);
    }
    if (rec.affected_users) {
      lines.push(`\n### Affected Users\n${rec.affected_users}`);
    }

    if (rec.likely_causes && rec.likely_causes.length > 0) {
      lines.push('\n### Likely Causes');
      rec.likely_causes.forEach((cause) => lines.push(`- ${cause}`));
    }

    if (rec.success_metrics && rec.success_metrics.length > 0) {
      lines.push('\n### Success Metrics');
      rec.success_metrics.forEach((metric) => lines.push(`- ${metric}`));
    }

    if (rec.risks && rec.risks.length > 0) {
      lines.push('\n### Risks & Considerations');
      rec.risks.forEach((risk) => lines.push(`- ${risk}`));
    }

    lines.push('\n---\n');

    // Epistemic Observations: Facts, Inferences, Hypotheses
    lines.push('## Epistemic Evidence Breakdown');

    if (rec.factual_observations && rec.factual_observations.length > 0) {
      lines.push('\n### 🟢 Observed Facts (Verified Evidence)');
      rec.factual_observations.forEach((f) => {
        const citations = f.evidence_ids?.length ? ` *[${f.evidence_ids.join(', ')}]*` : '';
        lines.push(`- ${f.statement}${citations}`);
      });
    }

    if (rec.inferences && rec.inferences.length > 0) {
      lines.push('\n### 🟡 Inferences (Derived Conclusions)');
      rec.inferences.forEach((inf) => {
        const citations = inf.evidence_ids?.length ? ` *[${inf.evidence_ids.join(', ')}]*` : '';
        lines.push(`- ${inf.statement}${citations}`);
      });
    }

    if (rec.hypotheses && rec.hypotheses.length > 0) {
      lines.push('\n### 🟣 Hypotheses (Platitude & Root Cause Theories)');
      rec.hypotheses.forEach((hyp) => {
        const citations = hyp.evidence_ids?.length ? ` *[${hyp.evidence_ids.join(', ')}]*` : '';
        lines.push(`- ${hyp.statement}${citations}`);
      });
    }

    lines.push('\n---\n');

    if (rec.conflicting_evidence && rec.conflicting_evidence.length > 0) {
      lines.push('## Tensions & Contradictory Signals');
      rec.conflicting_evidence.forEach((item) => lines.push(`- ⚠️ ${item}`));
      lines.push('\n---\n');
    }

    if (rec.disclosed_limitations && rec.disclosed_limitations.length > 0) {
      lines.push('## Disclosed Investigation Limitations');
      rec.disclosed_limitations.forEach((lim) => lines.push(`- ℹ️ ${lim}`));
      lines.push('\n---\n');
    }
  }

  // Evidence Ledger Items
  if (detail.evidence_ledger && Object.keys(detail.evidence_ledger).length > 0) {
    lines.push('## Authoritative Evidence Ledger');
    Object.values(detail.evidence_ledger).forEach((item) => {
      lines.push(`\n### [${item.source_type.toUpperCase()}] ${item.source_reference}`);
      lines.push(`- **Record ID:** \`${item.ledger_entry_id}\``);
      lines.push(`- **Finding:** ${item.finding}`);
      lines.push(`- **Support:** ${item.support_excerpt}`);
      lines.push(`- **Confidence:** \`${item.confidence}\``);
    });
    lines.push('\n---\n');
  }

  // Independent Critic Review
  if (detail.critic_review) {
    const critic = detail.critic_review;
    lines.push('## Independent Critic Review');
    lines.push(`**Verdict:** \`${critic.status}\` (Revisions Completed: ${critic.revisions_completed})`);
    if (critic.critique_summary) {
      lines.push(`\n${critic.critique_summary}`);
    }
    if (critic.issues_addressed && critic.issues_addressed.length > 0) {
      lines.push('\n**Addressed Weaknesses:**');
      critic.issues_addressed.forEach((issue) => lines.push(`- ${issue}`));
    }
    lines.push('\n---\n');
  }

  lines.push('*Exported from PMLytics AI — Decision-grade product discovery platform.*');
  return lines.join('\n');
}

export function generateSummaryClipboardText(detail: InvestigationDetailResponse): string {
  const title = detail.user_query;
  const decision = detail.recommendation?.recommendation || 'Analysis Complete';
  const confidence = detail.recommendation?.confidence || 'medium';
  const problem = detail.recommendation?.problem_statement || '';

  return `📊 *PMLytics AI Decision Brief*
*Question:* ${title}
*Decision:* ${decision}
*Confidence:* ${confidence.toUpperCase()}
${problem ? `\n*Problem:* ${problem.slice(0, 250)}...` : ''}

Full report: ${typeof window !== 'undefined' ? window.location.href : ''}`;
}

export function downloadMarkdownFile(filename: string, content: string): void {
  const blob = new Blob([content], { type: 'text/markdown;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = filename.endsWith('.md') ? filename : `${filename}.md`;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

export async function copyTextToClipboard(text: string): Promise<boolean> {
  try {
    if (navigator.clipboard && window.isSecureContext) {
      await navigator.clipboard.writeText(text);
      return true;
    }
    const textArea = document.createElement('textarea');
    textArea.value = text;
    textArea.style.position = 'fixed';
    textArea.style.left = '-999999px';
    document.body.appendChild(textArea);
    textArea.focus();
    textArea.select();
    const successful = document.execCommand('copy');
    document.body.removeChild(textArea);
    return successful;
  } catch {
    return false;
  }
}
